import { randomBytes, scrypt } from "node:crypto";
import { promisify } from "node:util";
import { writeFile, mkdir } from "node:fs/promises";
const root=new URL("../",import.meta.url);
await mkdir(new URL("functions/",root),{recursive:true});
const salt=randomBytes(32).toString("hex");
const hash=await promisify(scrypt)("Vector-emulator-test-passphrase-only",salt,64);
const masterRecord="scrypt$"+salt+"$"+hash.toString("hex");
await writeFile(new URL("functions/.env.local",root),"VECTOR_DATABASE_ID=ai-studio-vectorgame-560ec9bd-4e7c-4177-8021-3f5fed39406a\nVECTOR_STORAGE_BUCKET=demo-vector.appspot.com\nVECTOR_MASTER_PASSWORD_HASH="+masterRecord+"\n",{mode:0o600});
await writeFile(new URL("functions/.secret.local",root),"VECTOR_MASTER_PASSWORD_HASH="+masterRecord+"\n",{mode:0o600});
console.log("Ignored demo-only emulator settings prepared. Start Firebase with --project demo-vector.");
